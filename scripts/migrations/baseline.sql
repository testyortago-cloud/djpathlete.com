-- ONE-TIME BASELINE. Run this against prod ONCE, before the apply-migrations
-- workflow is ever allowed to run. It is not in supabase/migrations/ on
-- purpose: the workflow would otherwise try to apply it to itself.
--
-- WHY A SEPARATE LEDGER FROM supabase_migrations.schema_migrations.
-- That table is written by the Supabase MCP tool, which stamps its own
-- timestamp version and whatever name it was called with. The result, measured
-- on 2026-08-13: 152 rows against 209 files, versions like 20260812154832 that
-- no filename can produce, and names in two different styles (00202_funnels
-- alongside a bare shop_leads). Files and ledger cannot be matched by version
-- OR by name, so anything diffing them would replay dozens of already-applied
-- migrations against production.
--
-- This table is keyed on FILENAME, which is the thing git actually tracks and
-- the only identifier that cannot drift.
--
-- THE ASSUMPTION, AND HOW IT WAS CHECKED. Seeding a filename asserts "already
-- applied". That was verified before writing this: every table any migration
-- claims to CREATE - 146 of them - was confirmed present in prod. A migration
-- that only ALTERs is not covered by that check, so the residual risk is an
-- old ALTER that never ran and is now baselined as if it had. The alternative
-- (re-running 98 unrecorded migrations on prod) is far worse.
--
-- 00206_funnel_step_page_tree.sql is DELIBERATELY EXCLUDED - it has not been
-- applied, so the workflow`s first run applies it and proves itself on a
-- migration whose effect is known.

CREATE TABLE IF NOT EXISTS public.repo_migrations (
  filename   text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- One dollar-quoted string, not four. Adjacent dollar-quoted literals are NOT
-- concatenated in Postgres the way adjacent single-quoted ones are; $$a$$ $$b$$
-- is a syntax error.
COMMENT ON TABLE public.repo_migrations IS
  $$Filenames from supabase/migrations/ already applied to this database.
Written by .github/workflows/apply-migrations.yml, in the SAME transaction as
the migration itself. Distinct from supabase_migrations.schema_migrations,
which the Supabase MCP tooling owns and which cannot be matched to filenames.$$;

